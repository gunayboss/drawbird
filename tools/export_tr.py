"""Writes tools/i18n_content/tr.py: every Turkish text of the content pages in the one shape all translations share.

Run from the project root after editing content_*.py or ui_tr.py:  python tools/export_tr.py
"""
import io, os, pprint, sys
sys.path.insert(0, os.path.dirname(__file__))
from content_lessons import LESSONS
from content_birds import BIRDS
from content_pages import TEACHERS, FAQ, ABOUT, POSTS
from content_legal import LEGAL
from ui_tr import UI

data = {
    'UI': UI,
    'LESSONS': {L['slug']: {
        'title': L['title'], 'bird': L['bird'], 'cta': f"Şimdi kendi {L['acc']} çiz", 'intro': L['intro'],
        'steps': [[name, text] for name, text, _ in L['steps']], 'mistakes': L['mistakes'], 'facts': L['facts'],
    } for L in LESSONS},
    'BIRDS': {B['slug']: {
        'name': B['name'], 'cta': f"Kendi {B['acc']} çiz", 'lead': B['lead'], 'table': [v for _, v in B['table']],
        'body': B['body'], 'draw': B['draw'], 'own': B.get('own', ''),
    } for B in BIRDS},
    'PAGES': {
        'ogretmenler': {'title': TEACHERS['title'], 'desc': TEACHERS['desc'], 'html': TEACHERS['html'].strip()},
        'sss': {'title': FAQ['title'], 'desc': FAQ['desc'], 'items': [[q, a] for q, a in FAQ['items']]},
        'hakkinda': {'title': ABOUT['title'], 'desc': ABOUT['desc'], 'html': ABOUT['html'].strip()},
    },
    'LEGAL': LEGAL,
    'POSTS': {P['slug']: {'title': P['title'], 'desc': P['desc'], 'html': P['html'].strip()} for P in POSTS},
}
out = '"""Turkish source for all content translations. Generated by tools/export_tr.py; edit content_*.py instead."""\n\n'
out += ''.join(f'{k} = {pprint.pformat(v, width=200, sort_dicts=False)}\n\n' for k, v in data.items())
io.open(os.path.join(os.path.dirname(__file__), 'i18n_content', 'tr.py'), 'w', encoding='utf-8', newline='\n').write(out)
print('tr.py yazıldı')
